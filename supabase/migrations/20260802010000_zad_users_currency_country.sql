--
-- المشكلة: الكلاينت بيخزن اختيار البلد محلياً بس (MarketPrefs → SA/EG/TR) ومبيكتبهوش
-- للسيرفر خالص. وسيرفر-سايد، zad_users كان من غير عمود currency أصلآ — ومع ذلك
-- zad-telegram-bot كان بيعمل select("...currency") (index.ts:72)، فكانت بتقعد 400،
-- وuser.data بتترجع null → البوت شايف monthlyLimit=0 وcurrency="ر.س" افتراضية.
-- والنتيجة اللي شافها العميل: "قالي مفيش ولا ريال وأنا فلوسي بالمصري".
--
-- كمان zad-brain بيحط currency: "auto" (index.ts:430) — يعني العقل نفسه مبيعرفش
-- العملة، فأي مبلغ بيتكلم عنه بيتبني على عمود غير موجود.
--
-- الحل: عمودين على zad_users (currency + country)، العمودين nullable عشان مفيش
-- افتراض خاطئ (نفس قاعدة salary-cycle: null = مش معروف، مش افتراض). الكلاينت بيجيب
-- اختيار البلد من MarketPrefs فيكتبه هنا وقت اختيار السوق، والبوت/العقل بيقرأوا
-- القيمة الحقيقية، ولو null بيقولوا "غير معروف" بدل ما يخترعوا "ر.س".
--
-- ملاحظة: قيم العملة بتتوافق مع zad_locale_config (20260726080000):
--   EG → EGP، SA → SAR، TR → TRY.

alter table public.zad_users
  add column if not exists currency text,
  add column if not exists country text;

comment on column public.zad_users.currency is
  'رمز العملة (EGP/SAR/TRY) — بيجيب قيمة من اختيار السوق في الكلاينت (MarketPrefs) وقت اختيار البلد. null = لسه مش معروف، والـ AI ممنوع يفترض ر.س';
comment on column public.zad_users.country is
  'كود البلد (EG/SA/TR) من اختيار السوق في الكلاينت. null = لسه مش معروف. بيستخدم لكشف السفر/تغيير العملة ولهجة المحادثة';
