-- =====================================================
-- سياسة INSERT لـ `agent_logs` عشان التطبيق يقدر يسجّل وقوع لفة الوكيل.
--
-- الجدول اتعمل عن قصد من غير أي سياسة INSERT (migration 20260814152758):
-- "Written only by the edge function via the service_role key". ده كان صح وقتها،
-- لأن الكاتب الوحيد كان zad-core-intelligence بمفتاح service-role.
--
-- اللي اتغيّر: مسار الشات في التطبيق بيقع على الرد القرائي القديم لما لفة زاد-برين
-- تفشل، والمسار القديم مايقدرش يسجّل مصروف أصلاً (٤ عمليات مخزون/صيدلية بس، من غير
-- log_transaction). الفشل ده مكانش بيسيب أي أثر في أي مكان — لا `agent_actions`
-- (بيتكتب وقت النجاح بس) ولا هنا. النتيجة إن قناة كاملة ممكن تفضل واقعة أيام
-- والبيانات تقول إنها "مش مستخدمة" مش "بتفشل"، وده بالظبط اللي حصل: `app_chat`
-- عنده إجراء واحد مقابل ٤٤ لتليجرام، ومفيش طريقة تعرف بيها ده استخدام قليل ولا فشل
-- مخفي. التطبيق بيتكلم بمفتاح المستخدم مش service-role، فمحتاج سياسة صريحة.
--
-- الأمان: القراءة **مابتتغيّرش** — فاضلة `agent_logs_select_admin` (is_dashboard_admin)
-- زي ما migration 20260814211944 قفلها بعد ما اكتشف إن الـpayload بيسرّب بيانات
-- العملاء المالية. السياسة دي INSERT بس، ومربوطة بـ auth.uid() = user_id فالمستخدم
-- مايقدرش يكتب صف باسم حد تاني. `authenticated` بس — anon مالوش أي كتابة.
--
-- ملحوظة للكاتب في التطبيق: `user_id` لازم يتحط صراحة (NULL هيسقط في WITH CHECK)،
-- والـpayload هنا بيتقفل على سبب الفشل والقناة — ممنوع يتحط فيه أي محتوى برومبت أو
-- بيانات مالية، عشان مايرجعش نفس التسريب اللي الجدول اتقفل بسببه.
-- =====================================================

DROP POLICY IF EXISTS "agent_logs_insert_own" ON agent_logs;
CREATE POLICY "agent_logs_insert_own"
    ON agent_logs FOR INSERT
    TO authenticated
    WITH CHECK (auth.uid() = user_id);
